// Validate authored live assets and retire the former offline calculator.
import {readFile,writeFile} from 'node:fs/promises';
import {Script} from 'node:vm';
import {createHash} from 'node:crypto';
const file=name=>new URL(`./dist/${name}`,import.meta.url);
let [html,script,notice]=await Promise.all([readFile(file('live.html'),'utf8'),readFile(file('live.mjs'),'utf8'),readFile(new URL('./offline-notice.html',import.meta.url),'utf8')]);
const stateSource=await readFile(file('live-state.mjs'),'utf8');
const stateVersion=createHash('sha256').update(stateSource).digest('hex').slice(0,12);
script=script.replace(/from '\.\/live-state\.mjs(?:\?v=[a-f0-9]+)?'/,"from './live-state.mjs?v="+stateVersion+"'");
const jointVersion=createHash('sha256').update(await readFile(file('joint-sensors.mjs'),'utf8')).digest('hex').slice(0,12);
script=script.replace(/from '\.\/joint-sensors\.mjs(?:\?v=[a-f0-9]+)?'/,"from './joint-sensors.mjs?v="+jointVersion+"'");
const dynamicsVersion=createHash('sha256').update(await readFile(file('dynamics-sensors.mjs'),'utf8')).digest('hex').slice(0,12);
script=script.replace(/from '\.\/dynamics-sensors\.mjs(?:\?v=[a-f0-9]+)?'/,"from './dynamics-sensors.mjs?v="+dynamicsVersion+"'");
const proximityVersion=createHash('sha256').update(await readFile(file('proximity-sensors.mjs'),'utf8')).digest('hex').slice(0,12);
script=script.replace(/from '\.\/proximity-sensors\.mjs(?:\?v=[a-f0-9]+)?'/,"from './proximity-sensors.mjs?v="+proximityVersion+"'");
const liftVersion=createHash('sha256').update(await readFile(file('lift-control.mjs'),'utf8')).digest('hex').slice(0,12);
script=script.replace(/from '\.\/lift-control\.mjs(?:\?v=[a-f0-9]+)?'/,"from './lift-control.mjs?v="+liftVersion+"'");
const missionVersion=createHash('sha256').update(await readFile(file('mission.mjs'),'utf8')).digest('hex').slice(0,12);
script=script.replace(/from '\.\/mission\.mjs(?:\?v=[a-f0-9]+)?'/,"from './mission.mjs?v="+missionVersion+"'");
const handlingVersion=createHash('sha256').update(await readFile(file('handling-control.mjs'),'utf8')).digest('hex').slice(0,12);
script=script.replace(/from '\.\/handling-control\.mjs(?:\?v=[a-f0-9]+)?'/,"from './handling-control.mjs?v="+handlingVersion+"'");
const palletVersion=createHash('sha256').update(await readFile(file('pallet-perception.mjs'),'utf8')).digest('hex').slice(0,12);
script=script.replace(/from '\.\/pallet-perception\.mjs(?:\?v=[a-f0-9]+)?'/,"from './pallet-perception.mjs?v="+palletVersion+"'");
const driveVersion=createHash('sha256').update(await readFile(file('drive-estimator.mjs'),'utf8')).digest('hex').slice(0,12);
script=script.replace(/from '\.\/drive-estimator\.mjs(?:\?v=[a-f0-9]+)?'/,"from './drive-estimator.mjs?v="+driveVersion+"'");
const lidarVersion=createHash('sha256').update(await readFile(file('lidar-safety.mjs'),'utf8')).digest('hex').slice(0,12);
script=script.replace(/from '\.\/lidar-safety\.mjs(?:\?v=[a-f0-9]+)?'/,"from './lidar-safety.mjs?v="+lidarVersion+"'");
const dataVersion=createHash('sha256').update(await readFile(file('data.mjs'),'utf8')).digest('hex').slice(0,12);
script=script.replace(/from '\.\/data\.mjs(?:\?v=[a-f0-9]+)?'/,"from './data.mjs?v="+dataVersion+"'");
await writeFile(file('live.mjs'),script,'utf8');
const version=createHash('sha256').update(script).digest('hex').slice(0,12);
html=html.replace(/src="live\.mjs(?:\?v=[a-f0-9]+)?"/,'src="live.mjs?v='+version+'"');
await writeFile(file('live.html'),html,'utf8');
new Script(script.replace(/^import .*;$/gm,''),{filename:'live.mjs'});
if(!/src="live\.mjs\?v=[a-f0-9]+"/.test(html)||html.includes('app.mjs'))throw new Error('Live entry point required');
await writeFile(file('index.html'),html,'utf8');
await writeFile(file('offline.html'),notice,'utf8');
console.log('LIVE_ASSET_CHECK PASS: live entry point updated; former offline page now points to the local server.');
